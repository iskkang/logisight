'use strict';
// data_quality_flags의 일본어 표기.
//
// 플래그는 score.js가 한국어로 만든다. 채점 엔진에 언어를 넣지 않고, 출력 경계
// (프롬프트·행)에서만 옮긴다 — basis와 같은 방식이다.
//
// 옮기지 않으면 두 곳에서 샌다:
//  1) 화면 — 일본판 카드에 '결측 — 가중치 재분배'가 그대로 나온다.
//  2) 본문 — 모델이 프롬프트의 '결측'을 받아 「結測」이라 쓴다. 일본어에 없는 말이다.
//     실제로 발행분 4건이 전부 그렇게 나왔다.

const RULES = [
  // `${factor}: 결측 — 가중치 재분배`
  [/^(\w+): 결측 — 가중치 재분배$/, (m) => `${m[1]}: 欠測 — 加重を再配分`],
  // `비용: 유가 비교 구간 N일(월간 미만, 근사)`
  [/^비용: 유가 비교 구간 (\d+)일\(월간 미만, 근사\)$/, (m) => `コスト: 燃料油の比較期間 ${m[1]}日(1か月未満・近似)`],
  // `공급: 방향 미산출(관측 1건) — 기본값 stable`
  [/^공급: 방향 미산출\(관측 1건\) — 기본값 (\w+)$/, (m) => `供給: 方向を算出せず(観測1件) — 既定値 ${m[1]}`],
  // `공급: 중국 수급 보정 +0.5(b-3, …)`
  [/^공급: 중국 수급 보정 (.+)$/, (m) => `供給: 中国の需給補正 ${m[1]}`],
  // `수요: 한국 수출 비적용(상하이발 등 지리 불일치) — 모멘텀 결측`
  // 일본판에 '한국 수출'을 그대로 옮기면 읽는 쪽에 뜻이 없다. 무엇이 없는지만 남긴다.
  [/^수요: 한국 수출 비적용.*$/, () => '需要: 輸出モメンタムを本指標に適用できない(地理が不一致) — 欠測'],
];

/** 모르는 플래그는 원문 그대로 둔다 — 지우면 무슨 결측인지 알 수 없게 된다. */
function flagJa(flag) {
  const s = String(flag);
  for (const [re, to] of RULES) {
    const m = re.exec(s);
    if (m) return to(m);
  }
  return s;
}

function flagsFor(flags, lang) {
  const list = flags || [];
  return lang === 'ja' ? list.map(flagJa) : list;
}

module.exports = { flagJa, flagsFor, RULES };
